-- Initial PostgreSQL schema for the Digital Asset Management project.
-- Run this in Supabase SQL Editor on a NEW project/database.
-- Review the backend migration before using this schema with the application.

CREATE TABLE IF NOT EXISTS categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT DEFAULT '',
  icon TEXT DEFAULT 'fa-folder',
  color_class TEXT DEFAULT 'other-icon',
  created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS categories_name_lower_unique
  ON categories (LOWER(name));

CREATE TABLE IF NOT EXISTS assets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  filename TEXT NOT NULL,
  original_name TEXT NOT NULL,
  file_path TEXT NOT NULL,
  mime_type TEXT NOT NULL,
  file_type TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'Others',
  size_bytes BIGINT NOT NULL DEFAULT 0,
  tags TEXT DEFAULT '',
  description TEXT DEFAULT '',
  created_at TEXT NOT NULL,
  downloads_count BIGINT DEFAULT 0
);

CREATE TABLE IF NOT EXISTS activity_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action TEXT NOT NULL,
  asset_name TEXT NOT NULL,
  details TEXT DEFAULT '',
  timestamp TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS user_profile (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  role TEXT NOT NULL,
  avatar_url TEXT NOT NULL,
  bio TEXT DEFAULT '',
  storage_limit_mb INTEGER DEFAULT 20480
);

CREATE TABLE IF NOT EXISTS system_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS otp_sessions (
  phone TEXT PRIMARY KEY,
  otp TEXT NOT NULL,
  expires_at BIGINT NOT NULL
);

-- ==============================================================================
-- Supabase Storage Bucket & Access Policies
-- ==============================================================================
INSERT INTO storage.buckets (id, name, public)
VALUES ('dam-assets', 'dam-assets', true)
ON CONFLICT (id) DO NOTHING;

-- Allow public read access to uploaded assets
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE tablename = 'objects' AND policyname = 'Public Access for dam-assets'
  ) THEN
    CREATE POLICY "Public Access for dam-assets" ON storage.objects
      FOR ALL USING (bucket_id = 'dam-assets')
      WITH CHECK (bucket_id = 'dam-assets');
  END IF;
END $$;

